+ (void)storeBookmark:(NSURL*)url key:(NSString*)key {
  NSData* bookmark = [url bookmarkDataWithOptions:0
                   includingResourceValuesForKeys:nil
                                    relativeToURL:nil
                                            error:nil];
  [NSUserDefaults.standardUserDefaults
      setObject:bookmark
         forKey:[@"bookmark." stringByAppendingString:key]];
}

+ (void)clearBookmark:(NSString*)key {
  [NSUserDefaults.standardUserDefaults
      removeObjectForKey:[@"bookmark." stringByAppendingString:key]];
}

+ (NSURL*)urlForBookmark:(NSString*)key {
  NSData* bookmark = [NSUserDefaults.standardUserDefaults
      dataForKey:[@"bookmark." stringByAppendingString:key]];
  if (!bookmark) return nil;
  BOOL stale = NO;
  NSURL* url = [NSURL URLByResolvingBookmarkData:bookmark
                                         options:0
                                   relativeToURL:nil
                             bookmarkDataIsStale:&stale
                                           error:nil];
  // Left stale, a bookmark stops resolving after enough moves of the file.
  if (url && stale && [url startAccessingSecurityScopedResource]) {
    NSData* fresh = [url bookmarkDataWithOptions:0
                  includingResourceValuesForKeys:nil
                                   relativeToURL:nil
                                           error:nil];
    [url stopAccessingSecurityScopedResource];
    if (fresh) {
      [NSUserDefaults.standardUserDefaults
          setObject:fresh
             forKey:[@"bookmark." stringByAppendingString:key]];
    }
  }
  return url;
}

static NSMutableArray<NSURL*>* g_held;

+ (void)holdPickedFiles {
  for (NSURL* url in g_held) [url stopAccessingSecurityScopedResource];
  g_held = [NSMutableArray array];
  for (NSString* key in
       @[ @"games.360", @"games.og", @"mcpx", @"flash", @"hdd", @"eeprom" ]) {
    NSURL* url = [self urlForBookmark:key];
    if (url && [url startAccessingSecurityScopedResource]) [g_held addObject:url];
  }
}

+ (NSArray<NSString*>*)gameFolders {
  NSString* docs = NSSearchPathForDirectoriesInDomains(
                       NSDocumentDirectory, NSUserDomainMask, YES)
                       .firstObject;
  const BOOL x360 = [self console] == XenraConsole360;
  NSString* own =
      [docs stringByAppendingPathComponent:x360 ? @"Games" : @"Games OG"];
  [NSFileManager.defaultManager createDirectoryAtPath:own
                          withIntermediateDirectories:YES
                                           attributes:nil
                                                error:nil];
  NSURL* picked = [self urlForBookmark:x360 ? @"games.360" : @"games.og"];
  return picked ? @[ own, picked.path ] : @[ own ];
}

