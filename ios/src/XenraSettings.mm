static NSArray* CountryValues(void) {
  NSMutableArray* values = [NSMutableArray array];
  int value = 1;
  for (NSUInteger i = 0; i < CountryCodes().count; i++, value++) {
    if (value == 17 || value == 94) value++;
    [values addObject:[NSString stringWithFormat:@"%d", value]];
  }
  return values;
}

