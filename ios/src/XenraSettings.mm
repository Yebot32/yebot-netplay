static XenraSettingSection* TouchSection(void) {
  NSMutableArray* rows = [NSMutableArray arrayWithObject:
      Toggle(@"pad.visible", XS(@"Show touch controls"), nil, YES)];
  // An iPad has no Taptic Engine, so on one this row would do nothing.
  if (UIDevice.currentDevice.userInterfaceIdiom == UIUserInterfaceIdiomPhone) {
    [rows addObject:Toggle(@"pad.haptics", XS(@"Vibration"), nil, YES)];
  }
  [rows addObjectsFromArray:@[
    Slider(@"pad.opacity", XS(@"Controller Opacity"), nil, 0.25f, 1, 0.05f, @"0.85",
           kFraction),
    Slider(@"pad.scale", XS(@"Controller Scale"), nil, 0.5f, 2, 0.05f, @"1.00", kTimes),
